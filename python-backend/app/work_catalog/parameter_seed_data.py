def _parameter_row(
    wt_id: str,
    key: str,
    *,
    code: str,
    label: str,
    description: str,
    data_type: str,
    section: str,
    sort_order: int,
    unit: str | None = None,
    required: bool = False,
    min_number_value: float | int | None = None,
    max_number_value: float | int | None = None,
    vision_extractable: bool = False,
    manual_override_allowed: bool = True,
    default_text_value: str | None = None,
    default_number_value: float | int | None = None,
    default_boolean_value: bool | None = None,
    default_option_code: str | None = None,
    options: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    return {
        "_param_key": key,
        "_options": list(options or []),
        "id": build_work_type_parameter_id(wt_id, key),
        "work_type_id": f"wt_{wt_id}",
        "code": code,
        "slug": code,
        "name": label,
        "description": description,
        "data_type": data_type,
        "unit": unit,
        "section": section,
        "is_required": required,
        "sort_order": sort_order,
        "min_number_value": min_number_value,
        "max_number_value": max_number_value,
        "vision_extractable": vision_extractable,
        "manual_override_allowed": manual_override_allowed,
        "default_text_value": default_text_value,
        "default_number_value": default_number_value,
        "default_boolean_value": default_boolean_value,
        "default_option_code": default_option_code,
    }


def _number_param(
    wt_id: str,
    key: str,
    *,
    code: str,
    label: str,
    description: str,
    section: str,
    sort_order: int,
    unit: str,
    required: bool = False,
    min_number_value: float | int | None = None,
    max_number_value: float | int | None = None,
    vision_extractable: bool = False,
) -> dict[str, Any]:
    return _parameter_row(
        wt_id,
        key,
        code=code,
        label=label,
        description=description,
        data_type="number",
        section=section,
        sort_order=sort_order,
        unit=unit,
        required=required,
        min_number_value=min_number_value,
        max_number_value=max_number_value,
        vision_extractable=vision_extractable,
    )


